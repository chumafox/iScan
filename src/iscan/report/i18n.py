def get_strings(lang: str = "en") -> dict[str, str]:
    return STRINGS.get(lang, STRINGS["en"])


def detect_lang() -> str:
    try:
        language = locale.getlocale()[0] or ""
        if language.lower().startswith("ru"):
            return "ru"
    except Exception:
        pass
    return "en"
